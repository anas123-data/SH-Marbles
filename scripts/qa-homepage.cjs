const { chromium } = require('playwright');
const { default: AxeBuilder } = require('@axe-core/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

async function main() {
  const output = path.resolve('output/phase-5');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: process.env.QA_BROWSER_CHANNEL || 'msedge' });
  try {
    const context = await browser.newContext({ acceptDownloads: true, permissions: ['clipboard-read', 'clipboard-write'] });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
    const result = { widths: [], interactions: [], accessibility: [], errors };
    for (const width of [375,390,430,768,1024,1440,1920]) {
      await page.setViewportSize({width,height:1000});
      const response = await page.goto('http://127.0.0.1:3000/', {waitUntil:'networkidle'});
      assert.equal(response.status(),200);
      await page.evaluate(() => document.fonts.ready);
      for (const section of ['#collections','#piece-study','#material','#bespoke','#craft','#trade','#project']) {
        await page.locator(section).scrollIntoViewIfNeeded();
        await page.waitForTimeout(100);
      }
      await page.waitForFunction(() => [...document.images].every(img => img.complete && img.naturalWidth>0));
      await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
      await page.waitForTimeout(900);
      const data = await page.evaluate(() => ({width:innerWidth,documentWidth:document.documentElement.scrollWidth,h1Count:document.querySelectorAll('h1').length,images:[...document.images].every(i=>i.alt && i.naturalWidth>0),badAnchors:[...document.querySelectorAll('a[href^="#"]')].filter(a=>!document.querySelector(a.getAttribute('href'))).map(a=>a.getAttribute('href'))}));
      await page.screenshot({path:path.join(output,`home-${width}.png`),fullPage:true});
      if(width===390 || width===1440) await page.screenshot({path:path.join(output,`hero-${width}.png`)});
      assert.ok(data.documentWidth<=width,`Overflow at ${width}: ${data.documentWidth}`);
      assert.equal(data.h1Count,1); assert.ok(data.images); assert.equal(data.badAnchors.length,0);
      result.widths.push(data);
    }
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:3000/');
    await page.keyboard.press('Tab');
    assert.ok(await page.locator('.skip-link').evaluate(e=>e===document.activeElement));
    result.interactions.push('Visible keyboard skip link');
    await page.locator('.collection-basins').click();
    assert.equal(await page.getByRole('tab',{name:'Basins',exact:true}).getAttribute('aria-selected'),'true');
    await page.getByRole('tab',{name:'Basins',exact:true}).focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.getByRole('tab',{name:'Objects',exact:true}).getAttribute('aria-selected'),'true');
    await page.keyboard.press('Home');
    assert.equal(await page.getByRole('tab',{name:'Tables',exact:true}).getAttribute('aria-selected'),'true');
    await page.getByRole('button',{name:'Another perspective'}).click();
    assert.equal(await page.getByRole('button',{name:'Main view'}).getAttribute('aria-pressed'),'true');
    result.interactions.push('Collection cards select/focus correct tab; keyboard arrows/Home; alternate image');
    await page.getByRole('radio',{name:'Warm & understated'}).check();
    await page.waitForFunction(()=>document.querySelector('.material-image img').complete);
    assert.match(await page.locator('.material-feedback').textContent(),/warm tones/);
    result.interactions.push('Material selection updates image and descriptive status');
    const baseAxe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    result.accessibility.push({state:'desktop',violations:baseAxe.violations});
    await page.getByRole('button',{name:'Plan a piece like this'}).click();
    const dialog = page.getByRole('dialog');
    assert.ok(await dialog.isVisible());
    assert.equal(await page.locator('#brief-interest').inputValue(),'A marble table');
    await page.locator('#brief-space').fill('Living room / sample destination');
    await page.locator('#brief-details').fill('One table, dimensions to discuss.');
    await page.getByRole('button',{name:'Copy brief',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.brief-status').textContent.includes('copied'));
    assert.match(await page.locator('.brief-status').textContent(),/copied/);
    const clipboard = await page.evaluate(()=>navigator.clipboard.readText());
    assert.match(clipboard,/One table, dimensions to discuss/);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button',{name:'Download brief',exact:true}).click();
    const download = await downloadPromise;
    await download.saveAs(path.join(output,'test-project-brief.txt'));
    assert.match(fs.readFileSync(path.join(output,'test-project-brief.txt'),'utf8'),/This brief has not been submitted/);
    const dialogAxe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    result.accessibility.push({state:'project-dialog',violations:dialogAxe.violations});
    await page.keyboard.press('Escape');
    assert.ok(!(await dialog.isVisible()));
    assert.ok(await page.getByRole('button',{name:'Plan a piece like this'}).evaluate(e=>e===document.activeElement));
    assert.equal(await page.evaluate(()=>document.body.style.overflow),'');
    result.interactions.push('Project context; editable draft; clipboard; text download; Escape; focus and scroll restoration');
    await page.getByRole('button',{name:'Plan a project together'}).click();
    assert.equal(await page.locator('#brief-interest').inputValue(),'An architectural / trade project');
    await page.getByRole('button',{name:'Close project brief'}).click();
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Menu',exact:true}).click();
    assert.equal(await page.locator('body').evaluate(e=>e.style.overflow),'hidden');
    const menuAxe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    result.accessibility.push({state:'mobile-menu',violations:menuAxe.violations});
    await page.keyboard.press('Escape');
    assert.ok(await page.getByRole('button',{name:'Menu',exact:true}).evaluate(e=>e===document.activeElement));
    await page.getByRole('button',{name:'Menu',exact:true}).click();
    await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:/Bespoke/}).click();
    assert.ok(!(await page.locator('#mobile-menu').isVisible()));
    await page.waitForURL('**/bespoke');
    assert.equal(new URL(page.url()).pathname,'/bespoke');
    result.interactions.push('Mobile menu navigation, Escape, focus trap supplied by native dialog, scroll unlock');
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
    assert.equal(await page.locator('h1').evaluate(e=>getComputedStyle(e).animationName),'none');
    result.interactions.push('Reduced-motion animation and scroll disabled');
    const mobileAxe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    result.accessibility.push({state:'mobile',violations:mobileAxe.violations});
    const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
    const staticPage=await nojs.newPage();
    await staticPage.goto('http://127.0.0.1:3000/');
    assert.equal(await staticPage.locator('h1').count(),1);
    assert.ok(await staticPage.locator('#collections').isVisible());
    result.interactions.push('Server-rendered primary content available without JavaScript');
    await nojs.close();
    const missing=await page.goto('http://127.0.0.1:3000/not-an-existing-page');
    assert.equal(missing.status(),404);
    // A deliberate 404 creates an expected browser network error; keep runtime errors separately.
    result.errors=errors.filter(e=>!e.includes('404'));
    fs.writeFileSync(path.join(output,'qa-results.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify({widths:result.widths,interactions:result.interactions,accessibility:result.accessibility.map(a=>({state:a.state,violations:a.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>n.target)}))})),errors:result.errors},null,2));
    assert.equal(result.errors.length,0);
    assert.ok(result.accessibility.every(a=>a.violations.length===0),'Accessibility violations in report');
  } finally {await browser.close()}
}
main().catch(error=>{console.error(error);process.exit(1)});
